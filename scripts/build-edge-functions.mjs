import {readFile,writeFile,mkdir} from 'node:fs/promises';
await mkdir('supabase/dashboard',{recursive:true});
for(const [name,helper] of [['admin-accounts','admin-handler'],['account-login','login-handler']]){
 const core=await readFile(`supabase/functions/_shared/${helper}.js`,'utf8');
 const entry=(await readFile(`supabase/functions/${name}/index.ts`,'utf8')).replace(/^import .*\n/,'');
 await writeFile(`supabase/dashboard/${name}.ts`,'// Generated by scripts/build-edge-functions.mjs. Paste this entire file in Supabase Dashboard.\n'+core+'\n'+entry);
}
